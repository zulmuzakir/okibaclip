func kindIcon(k history.Kind) *ui.SVG {
	switch k {
	case history.KindLink:
		return iconLink
	case history.KindColor:
		return iconPalette
	case history.KindImage:
		return iconImage
	case history.KindFiles:
		return iconFile
	}
	return iconClipboard
}
