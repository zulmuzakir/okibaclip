func hasFormat(offered []transfer.Format, f transfer.Format) bool { return slices.Contains(offered, f) }

// Classify turns clipboard data into a Capture per the capture rules. When
// it returns false, reason says why (empty when there is nothing to record).
func Classify(d transfer.Data, offered []transfer.Format, s settings.Settings, patterns []*regexp.Regexp) (history.Capture, string, bool) {
	if s.CaptureFiles && (hasFormat(offered, transfer.FileList) || hasFormat(offered, transfer.URIList)) {
		if files, err := d.Files(); err == nil && len(files) > 0 {
			return history.Capture{Kind: history.KindFiles, Text: strings.Join(files, "\n")}, "", true
		}
	}
	if hasFormat(offered, transfer.Text) {
		b, err := d.Read(transfer.Text)
		if err == nil && strings.TrimSpace(string(b)) != "" {
			if len(b) > history.MaxTextBytes {
				return history.Capture{}, "text over 1 MiB", false
			}
			text := string(b)
			for _, re := range patterns {
				if re.MatchString(text) {
					return history.Capture{}, "matches ignore pattern", false
				}
			}
			c := history.Capture{Kind: history.TextKind(text), Text: text}
			if c.Kind == history.KindText && hasFormat(offered, transfer.HTML) {
				if h, err := d.Read(transfer.HTML); err == nil && len(h) > 0 && len(h) <= history.MaxHTMLBytes {
					c.HTML = string(h)
				}
			}
			return c, "", true
		}
	}
	if s.CaptureImages && hasFormat(offered, transfer.PNG) {
		b, err := d.Read(transfer.PNG)
		if err != nil || len(b) == 0 {
			return history.Capture{}, "", false
		}
		if int64(len(b)) > int64(s.MaxImageMB)<<20 {
			return history.Capture{}, fmt.Sprintf("image over %d MB", s.MaxImageMB), false
		}
		cfg, err := png.DecodeConfig(bytes.NewReader(b))
		if err != nil {
			return history.Capture{}, "undecodable image", false
		}
		if !history.ImageDimsOK(cfg.Width, cfg.Height) {
			return history.Capture{}, "image over 40 megapixels", false
		}
		return history.Capture{Kind: history.KindImage, Image: b, Width: cfg.Width, Height: cfg.Height}, "", true
	}
	return history.Capture{}, "", false
}

var sensitiveMarkers = []string{
	"org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
	"com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type",
	"ExcludeClipboardContentFromMonitorProcessing", "Clipboard Viewer Ignore",
	"x-kde-passwordManagerHint",
}

const historyFlagFormat = "CanIncludeInClipboardHistory"

// IsSensitive reports whether the offered formats mark a copy as a secret.
func IsSensitive(native []string, portable []transfer.Format, readFormat func(transfer.Format) ([]byte, error)) bool {
	all := slices.Clone(native)
	for _, f := range portable {
		all = append(all, string(f))
	}
	for _, f := range all {
		if slices.Contains(sensitiveMarkers, f) {
			return true
		}
	}
	if slices.Contains(all, historyFlagFormat) && readFormat != nil {
		b, err := readFormat(transfer.Format(historyFlagFormat))
		if err == nil && len(b) >= 4 && b[0] == 0 && b[1] == 0 && b[2] == 0 && b[3] == 0 {
			return true
		}
	}
	return false
}
